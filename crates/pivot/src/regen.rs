//! Regeneration of the pivot parts after a refresh: cache records, `sharedItems`, the pivot
//! field `items` and `rowItems`/`colItems`, the way Excel writes them.
//!
//! Measured rules (oracle `pivot-refresh-*`, see `docs/architecture/pivot-tables.md`):
//!
//! * Excel shares items (`<sharedItems count=..>` with item elements) only for the fields that
//!   were on an axis when the cache was made; every other field carries the type flags and the
//!   value range and its records hold the value inline.
//! * A refresh rebuilds the shared items in order of first appearance in the source rows. Text is
//!   merged case-insensitively under the first spelling met. A numeric or text item that left the
//!   source stays at the end of the list with `u="1"` (and `m="1"` in the pivot field items) when
//!   the field has manual sort; a date item is dropped.
//! * The pivot field items keep the stored order of the items that are still there and append
//!   new items in order of first appearance (manual sort), else they are sorted.
//! * `rowItems`/`colItems` list the lines of the axis; `x` is the position in the field's items.

use std::collections::HashMap;

use open365_xlsx::{Attr, ParsedXml, RawXml, XmlElement};

use crate::SheetPivot;
use crate::compute::{AxisLine, Dataset, LineKind, PivotGrid};
use crate::model::{Axis, CacheSource, Func, PivotTable};
use crate::value::{ItemKey, Value, serial_to_iso};

/// The regenerated bytes of the three parts of one pivot.
pub(crate) struct Regenerated {
    pub cache: Vec<u8>,
    pub records: Vec<u8>,
    pub table: Vec<u8>,
}

/// The shared item list a field gets.
struct FieldPlan {
    shared: bool,
    date: bool,
    /// Items in shared order; the flag is `u` (not in the source any more).
    items: Vec<(Value, bool)>,
    index: HashMap<ItemKey, usize>,
    /// Calculated items (`f="1"`): they sit in the shared items without cache records.
    calc: std::collections::HashSet<ItemKey>,
}

fn plain(e: &XmlElement, local: &str, attrs: &[(&str, String)]) -> XmlElement {
    let mut x = e.sibling(local);
    x.head.attrs = attrs.iter().map(|(k, v)| Attr::plain(k, v)).collect();
    x
}

fn num_text(n: f64) -> String {
    format!("{n}")
}

fn is_date_serial(n: f64) -> bool {
    n.is_finite() && (0.0..2_958_466.0).contains(&n)
}

fn value_element(proto: &XmlElement, v: &Value, date: bool, unused: bool) -> XmlElement {
    let mut attrs: Vec<(&str, String)> = Vec::new();
    let local = match v {
        Value::Blank => "m",
        Value::Number(n) if date && is_date_serial(*n) => {
            attrs.push(("v", serial_to_iso(*n, false)));
            "d"
        }
        Value::Number(n) => {
            attrs.push(("v", num_text(*n)));
            "n"
        }
        Value::Text(t) => {
            attrs.push(("v", t.clone()));
            "s"
        }
        Value::Bool(b) => {
            attrs.push(("v", u8::from(*b).to_string()));
            "b"
        }
        Value::Error(e) => {
            attrs.push(("v", e.clone()));
            "e"
        }
    };
    if unused {
        attrs.push(("u", "1".into()));
    }
    plain(proto, local, &attrs)
}

/// Type flags and range of a field's current values (`sharedItems` attributes).
fn shared_attrs(values: &[Value], date: bool) -> Vec<(&'static str, String)> {
    let mut has_str = false;
    let mut has_blank = false;
    let mut has_other = false;
    let mut nums: Vec<f64> = Vec::new();
    let mut dates: Vec<f64> = Vec::new();
    for v in values {
        match v {
            Value::Blank => has_blank = true,
            Value::Text(_) => has_str = true,
            Value::Bool(_) | Value::Error(_) => has_other = true,
            Value::Number(n) if date && is_date_serial(*n) => dates.push(*n),
            Value::Number(n) => nums.push(*n),
        }
    }
    let has_num = !nums.is_empty();
    let has_date = !dates.is_empty();
    let kinds = usize::from(has_str)
        + usize::from(has_num)
        + usize::from(has_date)
        + usize::from(has_other);
    let mut out: Vec<(&'static str, String)> = Vec::new();
    if !has_str && !has_blank {
        out.push(("containsSemiMixedTypes", "0".into()));
    }
    if has_date && !has_str && !has_num && !has_other {
        out.push(("containsNonDate", "0".into()));
    }
    if has_date {
        out.push(("containsDate", "1".into()));
    }
    if !has_str {
        out.push(("containsString", "0".into()));
    }
    if has_blank {
        out.push(("containsBlank", "1".into()));
    }
    if kinds > 1 {
        out.push(("containsMixedTypes", "1".into()));
    }
    if has_num {
        out.push(("containsNumber", "1".into()));
        if nums.iter().all(|n| n.fract() == 0.0) {
            out.push(("containsInteger", "1".into()));
        }
        let min = nums.iter().copied().fold(f64::INFINITY, f64::min);
        let max = nums.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        out.push(("minValue", num_text(min)));
        out.push(("maxValue", num_text(max)));
    }
    if has_date {
        let min = dates.iter().copied().fold(f64::INFINITY, f64::min);
        let max = dates.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        out.push(("minDate", serial_to_iso(min, false)));
        // Excel stores the day after the last date.
        out.push(("maxDate", serial_to_iso(max.floor() + 1.0, false)));
    }
    if values.is_empty() || (!has_str && !has_blank && !has_num && !has_date && !has_other) {
        out.clear();
        out.push(("containsNonDate", "0".into()));
        out.push(("containsString", "0".into()));
        out.push(("containsBlank", "1".into()));
    }
    out
}

const MANAGED: [&str; 13] = [
    "containsSemiMixedTypes",
    "containsNonDate",
    "containsDate",
    "containsString",
    "containsBlank",
    "containsMixedTypes",
    "containsNumber",
    "containsInteger",
    "minValue",
    "maxValue",
    "minDate",
    "maxDate",
    "count",
];

fn func_name(f: Func) -> &'static str {
    match f {
        Func::Sum => "sum",
        Func::Count => "countA",
        Func::Average => "avg",
        Func::Max => "max",
        Func::Min => "min",
        Func::Product => "product",
        Func::CountNums => "count",
        Func::StdDev => "stdDev",
        Func::StdDevP => "stdDevP",
        Func::Var => "var",
        Func::VarP => "varP",
    }
}

/// `<i>` elements of one axis.
fn axis_elements(
    proto: &XmlElement,
    lines: &[AxisLine],
    levels: &[Option<usize>],
    posmap: &[Vec<Option<usize>>],
) -> Vec<XmlElement> {
    if levels.is_empty() {
        return vec![proto.sibling("i")];
    }
    let mapped = |level: usize, pos: usize| -> usize {
        match levels.get(level) {
            Some(Some(f)) => posmap
                .get(*f)
                .and_then(|m| m.get(pos))
                .copied()
                .flatten()
                .unwrap_or(pos),
            _ => pos,
        }
    };
    let x = |v: usize| -> XmlElement {
        let attrs = if v == 0 {
            Vec::new()
        } else {
            vec![("v", v.to_string())]
        };
        plain(proto, "x", &attrs)
    };
    let mut out = Vec::new();
    let mut prev: Vec<usize> = Vec::new();
    for l in lines {
        let mut attrs: Vec<(&str, String)> = Vec::new();
        let mut xs: Vec<XmlElement> = Vec::new();
        let mut r = 0;
        match l.kind {
            LineKind::Blank | LineKind::Subtotal => {
                attrs.push((
                    "t",
                    if l.kind == LineKind::Blank {
                        "blank"
                    } else {
                        l.func.map_or("default", func_name)
                    }
                    .into(),
                ));
                r = l.level;
                if let Some(p) = l.path.get(l.level) {
                    xs.push(x(mapped(l.level, *p)));
                }
            }
            LineKind::Grand => {
                attrs.push(("t", "grand".into()));
                xs.push(x(0));
            }
            LineKind::Item | LineKind::DataLeaf => {
                r = l
                    .path
                    .iter()
                    .zip(&prev)
                    .take_while(|(a, b)| a == b)
                    .count()
                    .min(l.path.len().saturating_sub(1));
                for (lv, p) in l.path.iter().enumerate().skip(r) {
                    xs.push(x(mapped(lv, *p)));
                }
            }
        }
        if r > 0 {
            attrs.push(("r", r.to_string()));
        }
        if let Some(d) = l.data.filter(|d| *d > 0) {
            attrs.push(("i", d.to_string()));
        }
        let mut e = plain(proto, "i", &attrs);
        e.children = xs.into_iter().map(RawXml::Element).collect();
        out.push(e);
        prev = l.path.clone();
    }
    out
}

fn child_index(root: &XmlElement, local: &str) -> Option<usize> {
    root.children
        .iter()
        .position(|c| c.as_element().is_some_and(|e| e.head.is_main(local)))
}

fn set_items_list(root: &mut XmlElement, local: &str, after: &[&str], elements: Vec<XmlElement>) {
    let mut list = root.sibling(local);
    list.head
        .attrs
        .push(Attr::plain("count", &elements.len().to_string()));
    list.children = elements.into_iter().map(RawXml::Element).collect();
    if let Some(i) = child_index(root, local) {
        root.children[i] = RawXml::Element(list);
        return;
    }
    let at = after
        .iter()
        .find_map(|a| child_index(root, a))
        .map_or(root.children.len(), |i| i + 1);
    root.children.insert(at, RawXml::Element(list));
}

/// Regenerates the cache definition, records and pivot table of `p` for the refreshed source.
/// `None` when the pivot has something this writer does not model (grouped or calculated fields
/// and items, a source that is not a worksheet range, no records part).
/// Rewrites the item positions (`x/@v`) of the user formats after the field items changed:
/// an old position becomes its item's new position, an item that is gone is dropped, and a
/// format that selected only gone items is removed.
fn remap_formats(root: &mut XmlElement, posmap: &[Vec<Option<usize>>]) {
    let Some(formats) = root
        .children
        .iter_mut()
        .filter_map(RawXml::as_element_mut)
        .find(|e| e.head.is_main("formats"))
    else {
        return;
    };
    formats.children.retain_mut(|node| {
        let Some(format) = node.as_element_mut() else {
            return true;
        };
        let Some(area) = format
            .children
            .iter_mut()
            .filter_map(RawXml::as_element_mut)
            .find(|e| e.head.is_main("pivotArea"))
        else {
            return true;
        };
        let Some(refs) = area
            .children
            .iter_mut()
            .filter_map(RawXml::as_element_mut)
            .find(|e| e.head.is_main("references"))
        else {
            return true;
        };
        for r in refs
            .children
            .iter_mut()
            .filter_map(RawXml::as_element_mut)
            .filter(|e| e.head.is_main("reference"))
        {
            let Some(fld) = r
                .head
                .attr("field")
                .and_then(|v| v.trim().parse::<usize>().ok())
            else {
                continue;
            };
            let Some(map) = posmap.get(fld).filter(|m| !m.is_empty()) else {
                continue;
            };
            let had_items = r.children.iter().any(|c| c.as_element().is_some());
            r.children.retain_mut(|c| {
                let Some(x) = c.as_element_mut().filter(|e| e.head.is_main("x")) else {
                    return true;
                };
                let old = x
                    .head
                    .attr("v")
                    .and_then(|v| v.trim().parse::<usize>().ok())
                    .unwrap_or(0);
                match map.get(old).copied().flatten() {
                    Some(new) => {
                        // Excel writes the position explicitly in format references (a
                        // `v="0"` stays), and leaves a bare `<x/>` alone.
                        if new != old || x.head.attr("v").is_some() {
                            x.head.set_attr("v", &new.to_string());
                        }
                        true
                    }
                    None => false,
                }
            });
            let left = r
                .children
                .iter()
                .filter(|c| c.as_element().is_some())
                .count();
            if had_items && left == 0 {
                return false;
            }
            if r.head.attr("count").is_some() {
                r.head.set_attr("count", &left.to_string());
            }
        }
        true
    });
    if formats.head.attr("count").is_some() {
        let n = formats.elements().count();
        formats.head.set_attr("count", &n.to_string());
    }
}

pub(crate) fn regenerate(
    p: &SheetPivot,
    data: &Dataset,
    grid: &PivotGrid,
    refreshed_date: f64,
    groups: &crate::model::CacheDefinition,
) -> Option<Regenerated> {
    let cache = &p.cache;
    let table = &p.table;
    let old_records = p.records.as_ref()?;
    if !matches!(cache.source, CacheSource::Worksheet { .. })
        // A group Excel drops on this refresh changes the field list: not regenerated here.
        || cache
            .fields
            .iter()
            .zip(&groups.fields)
            .any(|(old, new)| {
                // Only a numeric group on a source field can be dropped in place; a date
                // group that goes takes its derived fields along.
                old.group.is_some() != new.group.is_some()
                    && !(old.database_field && old.group.as_ref().is_some_and(|g| g.group_by.is_none()))
            })
        || data.columns.len() != cache.fields.len()
        || table.fields.len() != cache.fields.len()
    {
        return None;
    }
    let rows = data.rows;
    // Text is unified case-insensitively under the first spelling met, in every field.
    let columns: Vec<Vec<Value>> = data
        .columns
        .iter()
        .map(|col| {
            let mut first: HashMap<ItemKey, String> = HashMap::new();
            col.iter()
                .take(rows)
                .map(|v| match v {
                    Value::Text(t) => Value::Text(
                        first
                            .entry(ItemKey::of(v))
                            .or_insert_with(|| t.clone())
                            .clone(),
                    ),
                    other => other.clone(),
                })
                .collect()
        })
        .collect();
    let data = &Dataset {
        columns,
        rows: data.rows,
    };
    // Cache field xml elements, for the "was shared" test.
    let cache_xml = cache.xml();
    let cf_elems: Vec<&XmlElement> = cache_xml
        .root
        .child_main("cacheFields")?
        .elements()
        .filter(|e| e.head.is_main("cacheField"))
        .collect();
    if cf_elems.len() != cache.fields.len() {
        return None;
    }

    // Plan the shared items of every field.
    let mut plans: Vec<FieldPlan> = Vec::new();
    for (fi, cf) in cache.fields.iter().enumerate() {
        let pf = &table.fields[fi];
        let was_shared = cf_elems[fi]
            .child_main("sharedItems")
            .is_some_and(|s| s.head.attr("count").is_some());
        let on_axis = matches!(pf.axis, Some(Axis::Row | Axis::Col | Axis::Page));
        let shared = cf.database_field && (was_shared || on_axis || !pf.items.is_empty());
        let mut plan = FieldPlan {
            shared,
            date: cf.contains_date,
            items: Vec::new(),
            index: HashMap::new(),
            calc: cache
                .calculated_items
                .iter()
                .filter(|c| c.field == fi)
                .filter_map(|c| cf.item_values().get(c.item as usize))
                .map(ItemKey::of)
                .collect(),
        };
        if shared {
            for v in data.columns[fi].iter().take(rows) {
                let k = ItemKey::of(v);
                if !plan.index.contains_key(&k) {
                    plan.index.insert(k, plan.items.len());
                    plan.items.push((v.clone(), false));
                }
            }
            // Calculated items follow the items of the source (in their stored order).
            for v in cf.item_values() {
                let k = ItemKey::of(v);
                if plan.calc.contains(&k) && !plan.index.contains_key(&k) {
                    plan.index.insert(k, plan.items.len());
                    plan.items.push((v.clone(), false));
                }
            }
            if !plan.date && cf.group.is_none() {
                for v in &cf.shared {
                    let k = ItemKey::of(v);
                    if !plan.index.contains_key(&k) {
                        plan.index.insert(k, plan.items.len());
                        plan.items.push((v.clone(), true));
                    }
                }
            }
        }
        plans.push(plan);
    }

    // Cache definition.
    let mut cache_xml: ParsedXml = cache.xml().clone();
    cache_xml.root.head.remove_attr("refreshOnLoad");
    cache_xml
        .root
        .head
        .set_attr("recordCount", &rows.to_string());
    cache_xml
        .root
        .head
        .set_attr("refreshedDate", &format!("{refreshed_date}"));
    {
        let fields = cache_xml
            .root
            .children
            .iter_mut()
            .filter_map(RawXml::as_element_mut)
            .find(|e| e.head.is_main("cacheFields"))?;
        let mut fi = 0;
        for node in &mut fields.children {
            let Some(cf) = node
                .as_element_mut()
                .filter(|e| e.head.is_main("cacheField"))
            else {
                continue;
            };
            let plan = &plans[fi];
            if !cache.fields[fi].database_field {
                fi += 1;
                continue;
            }
            let proto = cf.sibling("sharedItems");
            let idx = cf.children.iter().position(|c| {
                c.as_element()
                    .is_some_and(|e| e.head.is_main("sharedItems"))
            });
            let mut si = idx
                .and_then(|i| cf.children[i].as_element().cloned())
                .unwrap_or(proto);
            si.children.clear();
            si.head
                .attrs
                .retain(|a| !(a.ns.is_none() && MANAGED.contains(&a.name.as_str())));
            let values: Vec<Value> = data.columns[fi].iter().take(rows).cloned().collect();
            for (k, v) in shared_attrs(&values, plan.date) {
                si.head.attrs.push(Attr::plain(k, &v));
            }
            if plan.shared {
                si.head
                    .attrs
                    .push(Attr::plain("count", &plan.items.len().to_string()));
                let vproto = si.sibling("m");
                si.children = plan
                    .items
                    .iter()
                    .map(|(v, u)| {
                        let mut e = value_element(&vproto, v, plan.date, *u);
                        if plan.calc.contains(&ItemKey::of(v)) {
                            e.head.attrs.push(Attr::plain("f", "1"));
                        }
                        RawXml::Element(e)
                    })
                    .collect();
            }
            match idx {
                Some(i) => cf.children[i] = RawXml::Element(si),
                None => cf.children.insert(0, RawXml::Element(si)),
            }
            fi += 1;
        }
    }

    // Grouped fields: bounds and items of the regrouped data.
    if let Some(fields) = cache_xml
        .root
        .children
        .iter_mut()
        .filter_map(RawXml::as_element_mut)
        .find(|e| e.head.is_main("cacheFields"))
    {
        for (fi, cf) in fields
            .children
            .iter_mut()
            .filter_map(RawXml::as_element_mut)
            .filter(|e| e.head.is_main("cacheField"))
            .enumerate()
        {
            let g = groups.fields.get(fi).and_then(|f| f.group.as_ref());
            if g.is_none() && cache.fields[fi].group.is_some() {
                cf.children
                    .retain(|c| c.as_element().is_none_or(|e| !e.head.is_main("fieldGroup")));
            }
            let Some(g) = g.filter(|g| !g.items.is_empty()) else {
                continue;
            };
            let Some(fg) = cf
                .children
                .iter_mut()
                .filter_map(RawXml::as_element_mut)
                .find(|e| e.head.is_main("fieldGroup"))
            else {
                continue;
            };
            for node in &mut fg.children {
                let Some(e) = node.as_element_mut() else {
                    continue;
                };
                if e.head.is_main("rangePr") {
                    if let Some(d) = g.start_date {
                        e.head.set_attr("startDate", &serial_to_iso(d, false));
                    }
                    if let Some(d) = g.end_date {
                        e.head.set_attr("endDate", &serial_to_iso(d, false));
                    }
                    if let Some(n) = g.start_num {
                        e.head.set_attr("startNum", &num_text(n));
                    }
                    if let Some(n) = g.end_num {
                        e.head.set_attr("endNum", &num_text(n));
                    }
                } else if e.head.is_main("groupItems") {
                    let proto = e.sibling("s");
                    e.head.set_attr("count", &g.items.len().to_string());
                    e.children = g
                        .items
                        .iter()
                        .map(|v| RawXml::Element(value_element(&proto, v, false, false)))
                        .collect();
                }
            }
        }
    }

    // Calculated items point at their shared item: the new index.
    if let Some(list) = cache_xml
        .root
        .children
        .iter_mut()
        .filter_map(RawXml::as_element_mut)
        .find(|e| e.head.is_main("calculatedItems"))
    {
        for ci in list
            .children
            .iter_mut()
            .filter_map(RawXml::as_element_mut)
            .filter(|e| e.head.is_main("calculatedItem"))
        {
            let Some(r) = ci
                .children
                .iter_mut()
                .filter_map(RawXml::as_element_mut)
                .find(|e| e.head.is_main("pivotArea"))
                .and_then(|a| {
                    a.children
                        .iter_mut()
                        .filter_map(RawXml::as_element_mut)
                        .find(|e| e.head.is_main("references"))
                })
                .and_then(|r| {
                    r.children
                        .iter_mut()
                        .filter_map(RawXml::as_element_mut)
                        .find(|e| e.head.is_main("reference"))
                })
            else {
                continue;
            };
            let field = r
                .head
                .attr("field")
                .and_then(|v| v.trim().parse::<usize>().ok());
            let Some(x) = r
                .children
                .iter_mut()
                .filter_map(RawXml::as_element_mut)
                .find(|e| e.head.is_main("x"))
            else {
                continue;
            };
            let old = x
                .head
                .attr("v")
                .and_then(|v| v.trim().parse::<usize>().ok())
                .unwrap_or(0);
            let new = field.and_then(|f| {
                let key = ItemKey::of(cache.fields.get(f)?.item_values().get(old)?);
                plans.get(f)?.index.get(&key).copied()
            });
            if let Some(new) = new {
                x.head.set_attr("v", &new.to_string());
            }
        }
    }

    // Records.
    let mut rec_xml: ParsedXml = old_records.xml().clone();
    {
        let root = &mut rec_xml.root;
        let r_proto = root.sibling("r");
        let mut out: Vec<RawXml> = Vec::with_capacity(rows);
        for row in 0..rows {
            let mut r = r_proto.clone();
            for (fi, cf) in cache.fields.iter().enumerate() {
                if !cf.database_field {
                    continue;
                }
                let v = data.columns[fi].get(row).cloned().unwrap_or(Value::Blank);
                let plan = &plans[fi];
                let e = if plan.shared {
                    let at = plan.index.get(&ItemKey::of(&v)).copied().unwrap_or(0);
                    plain(&r_proto, "x", &[("v", at.to_string())])
                } else {
                    value_element(&r_proto, &v, plan.date, false)
                };
                r.children.push(RawXml::Element(e));
            }
            out.push(RawXml::Element(r));
        }
        root.children = out;
        root.head.set_attr("count", &rows.to_string());
    }

    // Pivot table: field items, page selections, rowItems and colItems.
    let mut new_table: PivotTable = table.clone();
    new_table.set_location(&grid.location);
    let mut posmap: Vec<Vec<Option<usize>>> = vec![Vec::new(); table.fields.len()];
    let mut selections: HashMap<usize, Option<usize>> = HashMap::new();
    {
        let root = &mut new_table.xml_mut().root;
        let proto = root.sibling("item");
        let fields_el = root
            .children
            .iter_mut()
            .filter_map(RawXml::as_element_mut)
            .find(|e| e.head.is_main("pivotFields"))?;
        let mut fi = 0;
        for node in &mut fields_el.children {
            let Some(pf_el) = node
                .as_element_mut()
                .filter(|e| e.head.is_main("pivotField"))
            else {
                continue;
            };
            let pf = &table.fields[fi];
            let cf = &cache.fields[fi];
            let plan = &plans[fi];
            if groups.fields[fi].group.is_none() && cf.group.is_some() {
                // The group is gone: the items are the shared items again, in stored order.
                if let Some(list) = pf_el
                    .children
                    .iter_mut()
                    .filter_map(RawXml::as_element_mut)
                    .find(|e| e.head.is_main("items"))
                {
                    let mut items: Vec<RawXml> = (0..cf.shared.len())
                        .map(|k| RawXml::Element(plain(&proto, "item", &[("x", k.to_string())])))
                        .collect();
                    items.extend(
                        list.children
                            .iter()
                            .filter(|c| c.as_element().is_some_and(|e| e.head.attr("x").is_none()))
                            .cloned(),
                    );
                    list.head.set_attr("count", &items.len().to_string());
                    list.children = items;
                }
            }
            let idx = pf_el
                .children
                .iter()
                .position(|c| c.as_element().is_some_and(|e| e.head.is_main("items")));
            let on_axis = matches!(pf.axis, Some(Axis::Row | Axis::Col | Axis::Page));
            if let Some(g) = groups.fields[fi]
                .group
                .as_ref()
                .filter(|g| !g.items.is_empty())
            {
                // The items of a grouped field are its group items: the stored order of the
                // items that are still there (same label), then the new ones in index order.
                // Months are always in calendar order.
                if let Some(i) = idx
                    && let Some(list) = pf_el.children[i].as_element_mut()
                {
                    let old_items = cf.group.as_ref().map_or(&[][..], |o| o.items.as_slice());
                    let old_x: Vec<usize> = list
                        .elements()
                        .filter(|e| e.head.is_main("item"))
                        .filter_map(|e| e.head.attr("x").and_then(|x| x.parse().ok()))
                        .collect();
                    let order = crate::grouping::item_order(
                        old_items,
                        &old_x,
                        &g.items,
                        g.group_by.as_deref() == Some("months"),
                    );
                    let tail: Vec<RawXml> = list
                        .children
                        .iter()
                        .filter(|c| c.as_element().is_some_and(|e| e.head.attr("x").is_none()))
                        .cloned()
                        .collect();
                    let mut items: Vec<RawXml> = order
                        .iter()
                        .map(|k| RawXml::Element(plain(&proto, "item", &[("x", k.to_string())])))
                        .collect();
                    items.extend(tail);
                    list.head.set_attr("count", &items.len().to_string());
                    list.children = items;
                }
                fi += 1;
                continue;
            }
            if !plan.shared || (idx.is_none() && !on_axis) {
                fi += 1;
                continue;
            }
            // Old item elements by value.
            let mut old_by_key: HashMap<ItemKey, XmlElement> = HashMap::new();
            let mut tail: Vec<XmlElement> = Vec::new();
            let mut old_positions: Vec<Option<ItemKey>> = Vec::new();
            if let Some(i) = idx
                && let Some(items) = pf_el.children[i].as_element()
            {
                for it in items.elements().filter(|e| e.head.is_main("item")) {
                    match it.head.attr("x").and_then(|x| x.parse::<usize>().ok()) {
                        Some(x) => {
                            let key = cf.shared.get(x).map(ItemKey::of);
                            old_positions.push(key.clone());
                            if let Some(k) = key {
                                old_by_key.insert(k, it.clone());
                            }
                        }
                        None => tail.push(it.clone()),
                    }
                }
            }
            let mut order = grid.item_order.get(fi).cloned().unwrap_or_default();
            if order.is_empty() && !on_axis {
                // A field with items off the axes (the base of a group): the stored order of the
                // items still in the source, then the new ones as they appear.
                let used: HashMap<ItemKey, &Value> = plan
                    .items
                    .iter()
                    .filter(|(_, u)| !*u)
                    .map(|(v, _)| (ItemKey::of(v), v))
                    .collect();
                let mut seen: std::collections::HashSet<ItemKey> = std::collections::HashSet::new();
                for k in old_positions.iter().flatten() {
                    if let Some(v) = used.get(k)
                        && seen.insert(k.clone())
                    {
                        order.push((*v).clone());
                    }
                }
                for (v, u) in &plan.items {
                    if !*u && seen.insert(ItemKey::of(v)) {
                        order.push(v.clone());
                    }
                }
            }
            // (value, position in the computed order); retained items of a sorted field are
            // placed by the sort, those of a field sorted by a data field or by hand go last.
            let mut merged: Vec<(Value, Option<usize>)> = order
                .iter()
                .enumerate()
                .map(|(i, v)| (v.clone(), Some(i)))
                .collect();
            let known: std::collections::HashSet<ItemKey> = order.iter().map(ItemKey::of).collect();
            let retained: Vec<(Value, Option<usize>)> = plan
                .items
                .iter()
                .filter(|(v, u)| *u && !known.contains(&ItemKey::of(v)))
                .map(|(v, _)| (v.clone(), None))
                .collect();
            if !retained.is_empty() {
                merged.extend(retained);
                let sorted_by_label = matches!(pf.sort_type.as_str(), "ascending" | "descending")
                    && pf.sort_by.is_none();
                if sorted_by_label {
                    crate::compute::sort_items(&mut merged, pf.sort_type == "descending");
                }
            }
            let mut elements: Vec<XmlElement> = Vec::new();
            let mut map: Vec<Option<usize>> = vec![None; order.len()];
            let mut new_keys: Vec<ItemKey> = Vec::new();
            for (v, pos) in &merged {
                let key = ItemKey::of(v);
                let Some(&x) = plan.index.get(&key) else {
                    continue;
                };
                let mut item = old_by_key
                    .get(&key)
                    .cloned()
                    .unwrap_or_else(|| proto.clone());
                item.head
                    .attrs
                    .retain(|a| !(a.ns.is_none() && (a.name == "x" || a.name == "m")));
                if plan.items[x].1 {
                    item.head.attrs.push(Attr::plain("m", "1"));
                }
                item.head.attrs.push(Attr::plain("x", &x.to_string()));
                if let Some(p) = pos {
                    map[*p] = Some(elements.len());
                }
                new_keys.push(key);
                elements.push(item);
            }
            let n_items = elements.len();
            elements.extend(tail);
            let mut list = pf_el.sibling("items");
            list.head
                .attrs
                .push(Attr::plain("count", &elements.len().to_string()));
            list.children = elements.into_iter().map(RawXml::Element).collect();
            match idx {
                Some(i) => pf_el.children[i] = RawXml::Element(list),
                None => pf_el.children.insert(0, RawXml::Element(list)),
            }
            // Page selection: the old position's item in the new list.
            if matches!(pf.axis, Some(Axis::Page)) {
                let sel = table
                    .page_fields
                    .iter()
                    .find(|g| g.fld as usize == fi)
                    .and_then(|g| g.item)
                    .and_then(|s| old_positions.get(s as usize).cloned().flatten())
                    .and_then(|k| new_keys.iter().position(|n| *n == k));
                selections.insert(fi, sel.filter(|s| *s < n_items));
            }
            posmap[fi] = map;
            fi += 1;
        }
        // Page field selections.
        if let Some(pfs) = root
            .children
            .iter_mut()
            .filter_map(RawXml::as_element_mut)
            .find(|e| e.head.is_main("pageFields"))
        {
            for g in pfs.children.iter_mut().filter_map(RawXml::as_element_mut) {
                let Some(fld) = g.head.attr("fld").and_then(|v| v.parse::<usize>().ok()) else {
                    continue;
                };
                if g.head.attr("item").is_none() {
                    continue;
                }
                match selections.get(&fld).copied().flatten() {
                    Some(s) => g.head.set_attr("item", &s.to_string()),
                    None => g.head.remove_attr("item"),
                }
            }
        }
        remap_formats(root, &posmap);
        let row_els = axis_elements(&proto, &grid.row_items, &grid.row_levels, &posmap);
        set_items_list(root, "rowItems", &["rowFields", "pivotFields"], row_els);
        let col_els = axis_elements(&proto, &grid.col_items, &grid.col_levels, &posmap);
        set_items_list(
            root,
            "colItems",
            &["colFields", "rowItems", "pivotFields"],
            col_els,
        );
    }

    Some(Regenerated {
        cache: cache_xml.to_bytes(),
        records: rec_xml.to_bytes(),
        table: new_table.to_bytes(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const XML: &str = r#"<pivotTableDefinition xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><formats count="3"><format dxfId="1"><pivotArea dataOnly="0" labelOnly="1" outline="0"><references count="1"><reference field="0" count="1"><x v="2"/></reference></references></pivotArea></format><format dxfId="2"><pivotArea dataOnly="0" labelOnly="1" outline="0"><references count="2"><reference field="0" count="1"><x/></reference><reference field="1" count="1"><x v="1"/></reference></references></pivotArea></format><format dxfId="3"><pivotArea type="all" outline="0"/></format></formats></pivotTableDefinition>"#;

    fn formats_after(posmap: &[Vec<Option<usize>>]) -> String {
        let mut x = open365_xlsx::parse_xml(XML.as_bytes()).expect("parses");
        remap_formats(&mut x.root, posmap);
        String::from_utf8(x.to_bytes()).expect("utf8")
    }

    #[test]
    fn format_item_positions_follow_the_items() {
        // Field 0: a new item came first, so 0 -> 1, 2 -> 3. Field 1 is unchanged.
        let out = formats_after(&[vec![Some(1), Some(2), Some(3)], vec![Some(0), Some(1)]]);
        assert!(out.contains(r#"<x v="3"/>"#), "{out}");
        assert!(out.contains(r#"<x v="1"/>"#), "{out}");
        assert!(out.contains(r#"type="all""#), "whole-table format kept");
        assert!(out.contains(r#"<formats count="3">"#));
    }

    #[test]
    fn formats_of_a_removed_item_are_dropped() {
        // Old item 2 of field 0 is gone: its format goes, the others keep working.
        let out = formats_after(&[vec![Some(0), Some(1), None], vec![Some(0), Some(1)]]);
        assert!(!out.contains(r#"dxfId="1""#), "{out}");
        assert!(out.contains(r#"dxfId="2""#), "{out}");
        assert!(out.contains(r#"<formats count="2">"#), "{out}");
    }
}
